// Paths keep the bitmap lettering independent of installed fonts and SVG renderers.
export function pixelText(value, x, y, size = 1, color = '#ffffff') {
  let path = '';
  [...String(value).toUpperCase()].forEach((character, index) => {
    const glyph = glyphs[character];
    if (!glyph) throw new Error(`Unsupported pixel glyph: ${character}`);
    glyph.forEach((row, rowIndex) => {
      [...row].forEach((cell, columnIndex) => {
        if (cell === '1') {
          const px = x + (index * 6 + columnIndex) * size;
          const py = y + rowIndex * size;
          path += `M${px} ${py}h${size}v${size}h-${size}z`;
        }
      });
    });
  });
  return `<path fill="${color}" d="${path}"/>`;
}

export const pixelWidth = (value, size = 1) => Math.max(0, String(value).length * 6 - 1) * size;
